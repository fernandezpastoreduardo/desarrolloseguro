#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

readonly SOURCE_IMAGE=${SOURCE_IMAGE:-pgvector/pgvector:0.8.7-pg17-bookworm}
readonly TARGET_IMAGE=${TARGET_IMAGE:-desarrolloseguro-postgres:pg19-candidate}
readonly RUN_ID="ds-pg-upgrade-$(date +%s)-$$"
readonly SOURCE_CONTAINER="$RUN_ID-source"
readonly TARGET_CONTAINER="$RUN_ID-target"
readonly SOURCE_VOLUME="$RUN_ID-source-data"
readonly TARGET_VOLUME="$RUN_ID-target-data"
readonly DATABASE_NAME=desarrollo_seguro
readonly APPLICATION_ROLE=ds_migrator
readonly ADMIN_ROLE=ds_migration_admin
readonly FIXTURE_PASSWORD=fixture-only-not-a-production-secret

started_source=0
started_target=0

cleanup() {
  local status=$?
  trap - EXIT ERR
  set +e
  if (( started_target == 1 )); then docker rm --force "$TARGET_CONTAINER" >/dev/null 2>&1; fi
  if (( started_source == 1 )); then docker rm --force "$SOURCE_CONTAINER" >/dev/null 2>&1; fi
  docker volume rm "$TARGET_VOLUME" "$SOURCE_VOLUME" >/dev/null 2>&1
  exit "$status"
}
trap cleanup EXIT

docker image inspect "$SOURCE_IMAGE" >/dev/null 2>&1 || docker pull "$SOURCE_IMAGE"
docker image inspect "$TARGET_IMAGE" >/dev/null 2>&1 || docker pull "$TARGET_IMAGE"
docker volume create "$SOURCE_VOLUME" >/dev/null
docker volume create "$TARGET_VOLUME" >/dev/null

start_database() {
  local name=$1 volume=$2 mount_path=$3 image=$4 user=$5 database=$6
  docker run --detach \
    --name "$name" \
    --env "POSTGRES_USER=$user" \
    --env "POSTGRES_PASSWORD=$FIXTURE_PASSWORD" \
    --env "POSTGRES_DB=$database" \
    --mount "type=volume,src=$volume,dst=$mount_path" \
    "$image" >/dev/null
}

wait_for_database() {
  local name=$1 user=$2 database=$3 attempt status
  for attempt in $(seq 1 120); do
    if docker exec "$name" pg_isready --username "$user" --dbname "$database" >/dev/null 2>&1; then
      return 0
    fi
    status=$(docker inspect --format '{{.State.Status}}' "$name")
    if [[ $status == exited || $status == dead ]]; then
      printf 'PostgreSQL migration fixture exited before becoming ready.\n' >&2
      docker logs --tail 40 "$name" >&2 || true
      return 1
    fi
    sleep 1
  done
  printf 'PostgreSQL migration fixture failed to become ready.\n' >&2
  docker logs --tail 40 "$name" >&2 || true
  return 1
}

start_database "$SOURCE_CONTAINER" "$SOURCE_VOLUME" /var/lib/postgresql/data "$SOURCE_IMAGE" ds_bootstrap postgres
started_source=1
start_database "$TARGET_CONTAINER" "$TARGET_VOLUME" /var/lib/postgresql "$TARGET_IMAGE" "$ADMIN_ROLE" "$ADMIN_ROLE"
started_target=1
wait_for_database "$SOURCE_CONTAINER" ds_bootstrap postgres
wait_for_database "$TARGET_CONTAINER" "$ADMIN_ROLE" "$ADMIN_ROLE"

docker exec "$SOURCE_CONTAINER" psql --set ON_ERROR_STOP=1 --username ds_bootstrap --dbname postgres \
  --command "CREATE ROLE $APPLICATION_ROLE LOGIN PASSWORD '$FIXTURE_PASSWORD' NOSUPERUSER NOCREATEDB NOCREATEROLE;"
for role in ds_api ds_worker ds_retention; do
  docker exec "$SOURCE_CONTAINER" psql --set ON_ERROR_STOP=1 --username ds_bootstrap --dbname postgres \
    --command "CREATE ROLE $role LOGIN PASSWORD '$FIXTURE_PASSWORD' NOSUPERUSER NOCREATEDB NOCREATEROLE;"
done
docker exec "$SOURCE_CONTAINER" createdb --username ds_bootstrap --owner "$APPLICATION_ROLE" "$DATABASE_NAME"
docker exec --interactive "$SOURCE_CONTAINER" psql --set ON_ERROR_STOP=1 --username ds_bootstrap --dbname "$DATABASE_NAME" <<'SQL'
CREATE EXTENSION vector;
CREATE TABLE ds_schema_migrations (version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());
INSERT INTO ds_schema_migrations(version) VALUES ('031_grumphya_hostname_redirect_evidence');
CREATE TABLE migration_probe (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL,
  embedding vector(3) NOT NULL
);
CREATE INDEX migration_probe_embedding_idx
  ON migration_probe USING hnsw (embedding vector_cosine_ops);
INSERT INTO migration_probe (category, embedding) VALUES
  ('verified', '[1,0,0]'),
  ('pending', '[0,1,0]');
GRANT CONNECT ON DATABASE desarrollo_seguro TO ds_api, ds_worker, ds_retention;
GRANT USAGE ON SCHEMA public TO ds_api, ds_worker, ds_retention;
SQL

source_version=$(docker exec "$SOURCE_CONTAINER" psql --tuples-only --no-align --username ds_bootstrap --dbname postgres \
  --command 'SHOW server_version_num;')
source_rows=$(docker exec "$SOURCE_CONTAINER" psql --tuples-only --no-align --username ds_bootstrap --dbname "$DATABASE_NAME" \
  --command 'SELECT count(*) FROM migration_probe;')
[[ $source_version -ge 170000 && $source_version -lt 180000 && $source_rows == 2 ]]

printf 'Restoring a synthetic PostgreSQL 17 cluster into a clean PostgreSQL 19 volume.\n'
set -o pipefail
docker exec "$SOURCE_CONTAINER" pg_dumpall --username ds_bootstrap --no-password \
  | docker exec --interactive "$TARGET_CONTAINER" psql --set ON_ERROR_STOP=1 --username "$ADMIN_ROLE" --dbname "$ADMIN_ROLE"

target_version=$(docker exec "$TARGET_CONTAINER" psql --tuples-only --no-align --username "$ADMIN_ROLE" --dbname "$ADMIN_ROLE" \
  --command 'SHOW server_version_num;')
target_rows=$(docker exec "$TARGET_CONTAINER" psql --tuples-only --no-align --username "$ADMIN_ROLE" --dbname "$DATABASE_NAME" \
  --command 'SELECT count(*) FROM migration_probe;')
target_migrations=$(docker exec "$TARGET_CONTAINER" psql --tuples-only --no-align --username "$ADMIN_ROLE" --dbname "$DATABASE_NAME" \
  --command 'SELECT count(*) FROM ds_schema_migrations;')
target_vector=$(docker exec "$TARGET_CONTAINER" psql --tuples-only --no-align --username "$ADMIN_ROLE" --dbname "$DATABASE_NAME" \
  --command "SELECT extversion FROM pg_extension WHERE extname = 'vector';")
target_index=$(docker exec "$TARGET_CONTAINER" psql --tuples-only --no-align --username "$ADMIN_ROLE" --dbname "$DATABASE_NAME" \
  --command "SELECT count(*) FROM pg_indexes WHERE indexname = 'migration_probe_embedding_idx';")
target_roles=$(docker exec "$TARGET_CONTAINER" psql --tuples-only --no-align --username "$ADMIN_ROLE" --dbname postgres \
  --command "SELECT count(*) FROM pg_roles WHERE rolname IN ('ds_bootstrap', 'ds_migrator', 'ds_api', 'ds_worker', 'ds_retention');")
target_permissions=$(docker exec "$TARGET_CONTAINER" psql --tuples-only --no-align --username "$ADMIN_ROLE" --dbname postgres \
  --command "SELECT count(*) FROM pg_database d JOIN pg_roles r ON r.rolname = 'ds_api' WHERE d.datname = 'desarrollo_seguro' AND has_database_privilege(r.oid, d.oid, 'CONNECT');")

[[ $target_version -ge 190000 && $target_version -lt 200000 ]]
[[ $target_rows == "$source_rows" && $target_migrations == 1 ]]
[[ $target_vector == 0.8.7 && $target_index == 1 ]]
[[ $target_roles == 5 && $target_permissions == 1 ]]

printf 'PostgreSQL major-upgrade rehearsal passed: source=%s target=%s pgvector=%s rows=%s roles=%s; source volume remained unchanged.\n' \
  "$source_version" "$target_version" "$target_vector" "$target_rows" "$target_roles"
